create extension if not exists btree_gist;

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  resource_id bigint not null references public.resources(id) on delete cascade,
  participant_id bigint not null references public.participants(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint reservations_valid_time check (ends_at > starts_at),
  constraint reservations_do_not_overlap
    exclude using gist (
      resource_id with =,
      tstzrange(starts_at, ends_at, '[)') with &&
    )
);

create index if not exists reservations_resource_starts_at_idx
  on public.reservations (resource_id, starts_at);

grant select, insert on public.reservations to authenticated;
grant usage, select on sequence public.reservations_id_seq to authenticated;

alter table public.reservations enable row level security;

create policy "Group members can view reservations"
  on public.reservations for select
  using (
    exists (
      select 1
      from public.resources r
      join public.group_members gm on gm.group_id = r.group_id
      join public.participants p on p.id = gm.participant_id
      where r.id = reservations.resource_id
        and p.user_id = (select auth.uid())
    )
  );

create policy "Group members can reserve resources"
  on public.reservations for insert
  with check (
    exists (
      select 1
      from public.resources r
      join public.group_members gm on gm.group_id = r.group_id
      join public.participants p on p.id = gm.participant_id
      where r.id = reservations.resource_id
        and gm.participant_id = reservations.participant_id
        and p.user_id = (select auth.uid())
    )
  );
